// Run only in a fresh disposable profile and data directory (see run-smoke.py).
async function runLanguageSmoke() {
  const checks = [];
  const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  const resultPath = PathUtils.join(Zotero.DataDirectory.dir, 'smoke-result.json');
  try {
    const api = Zotero.LanguageCompleter;
    const win = Zotero.getMainWindow();
    assert(Zotero.DataDirectory.dir.includes('zotero-language-smoke-'), 'isolated data directory');
    api.auto = false;
    async function article(title, language = '', extra = '') {
      const item = new Zotero.Item('journalArticle');
      item.setField('title', title); item.setField('language', language); item.setField('extra', extra);
      item.setCreators([{ firstName: 'Test', lastName: 'Author', creatorType: 'author' }]);
      await item.saveTx(); return item;
    }
    const cn = await article('东海陆架盆地断裂岩浆活动对氦气富集的控制作用', '', 'Citation Key: preserved_key');
    const en = await article('The influence of fault activity on helium accumulation in sedimentary basins');
    en.setField('abstractNote', 'This study investigates the influence of fault activity on the migration and accumulation of helium in sedimentary basins. Geological and geochemical data indicate that deep faults provide pathways for mantle gases and control the spatial distribution of natural gas reservoirs.');
    await en.saveTx();
    const keep = await article('已有语言的文献条目不应被修改', 'en-US');
    const short = await article('Helium');
    const changed = await article('断裂活动对深部氦气运移和富集的控制作用');
    const note = new Zotero.Item('note'); note.setNote('A note should never be classified'); await note.saveTx();
    let rows = await api.scan('library', win);
    assert(rows.some(r => r.id === cn.id && r.proposed === 'zh-CN'), 'Chinese proposal');
    assert(rows.some(r => r.id === en.id && r.proposed === 'en'), 'English proposal');
    assert(!rows.some(r => r.id === keep.id || r.id === note.id), 'existing language and notes excluded');
    assert(rows.some(r => r.id === short.id && !r.proposed), 'ambiguous title excluded');
    changed.setField('title', '预览之后被用户修改的另一篇文献'); await changed.saveTx();
    const result = await api.apply(rows.filter(r => r.proposed));
    assert(result.applied === 2 && result.skipped === 1, 'write only unchanged proposals');
    assert(cn.getField('language') === 'zh-CN' && en.getField('language') === 'en', 'languages persisted');
    assert(cn.getField('extra') === 'Citation Key: preserved_key' && cn.getCreators()[0].lastName === 'Author', 'citation key and author preserved');
    const journal = JSON.parse(await IOUtils.readUTF8(result.path));
    assert(journal.entries.filter(r => r.status === 'applied').length === 2, 'durable journal');
    en.setField('language', 'fr'); await en.saveTx();
    const undo = await api.undo();
    assert(undo.restored === 1 && undo.skipped === 1, 'rollback skips subsequently edited language');
    assert(!cn.getField('language') && en.getField('language') === 'fr', 'rollback values verified');
    const cancelled = await api.apply((await api.scan('library', win)).filter(r => r.proposed), 'manual', () => {}, () => true);
    assert(cancelled.applied === 0 && !cn.getField('language'), 'cancellation preserves items');
    assert(win.document.getElementById('language-completer-menu'), 'tools menu registered');
    const dialog = api.open(win);
    for (let i = 0; i < 80 && !dialog.document.getElementById('scan'); i++) await Zotero.Promise.delay(100);
    await Zotero.Promise.delay(500);
    assert(dialog.document.getElementById('scan'), 'privileged dialog loaded');
    dialog.document.getElementById('scan').click();
    for (let i = 0; i < 80 && dialog.document.getElementById('scan').disabled; i++) await Zotero.Promise.delay(100);
    assert(dialog.document.querySelectorAll('#results tr').length > 0, 'preview table rendered');
    assert(dialog.document.getElementById('count').textContent.includes('可补全'), 'preview summary rendered');
    assert(dialog.document.querySelector('#results tr.needs-review .language-result').textContent === '待确认', 'uncertain rows marked for yellow highlight');
    assert([...dialog.document.querySelectorAll('.language-choice')].every(e => e.style.display === 'none'), 'automatic results shown first with editors hidden');
    const sortedRows = [...dialog.document.querySelectorAll('#results tr')];
    const firstReady = sortedRows.findIndex(r => !r.classList.contains('needs-review'));
    assert(firstReady > 0 && sortedRows.slice(firstReady).every(r => !r.classList.contains('needs-review')), 'unresolved rows sorted before all ready rows');
    const batchFind = () => [...dialog.document.querySelectorAll('.language-choice')].find(e => e.getAttribute('aria-label') === '选择语言：' + short.getField('title')).closest('tr');
    assert(!batchFind().querySelector('input').disabled, 'uncertain row checkbox enabled');
    dialog.document.getElementById('select-review').click();
    assert(!dialog.document.getElementById('batch-en').disabled, 'select all uncertain enables batch action');
    dialog.document.getElementById('batch-en').click();
    assert(batchFind().querySelector('.language-result').textContent === '英文 · en', 'batch English updates uncertain preview');
    assert(!short.getField('language'), 'batch assignment does not write Zotero');
    assert([...dialog.document.querySelectorAll('.language-result')].some(e => e.textContent === '中文 · zh-CN'), 'batch assignment preserves already detected language');
    dialog.document.getElementById('scan').click();
    for (let i = 0; i < 80 && dialog.document.getElementById('scan').disabled; i++) await Zotero.Promise.delay(100);
    dialog.document.getElementById('select-review').click();
    dialog.document.getElementById('batch-zh').click();
    assert(batchFind().querySelector('.language-result').textContent === '中文 · zh-CN', 'batch Chinese updates uncertain preview');
    dialog.document.getElementById('scan').click();
    for (let i = 0; i < 80 && dialog.document.getElementById('scan').disabled; i++) await Zotero.Promise.delay(100);
    dialog.document.getElementById('select-review').click();
    dialog.document.getElementById('clear-review').click();
    assert(dialog.document.getElementById('batch-en').disabled, 'clear uncertain selection disables batch');
    const listHeight = dialog.document.querySelector('.table-wrap').getBoundingClientRect().height;
    dialog.document.getElementById('focus-list').click();
    await Zotero.Promise.delay(100);
    assert(dialog.document.querySelector('.table-wrap').getBoundingClientRect().height > listHeight, 'expand list increases available table height');
    dialog.document.getElementById('focus-list').click();
    assert(!dialog.document.body.classList.contains('list-expanded'), 'full interface restored');
    const controls = [...dialog.document.querySelectorAll('.language-choice')];
    assert(controls.length > 0 && controls.every(c => c.querySelectorAll('button').length === 3), 'three direct language buttons per row');
    assert([...dialog.document.querySelectorAll('#results input')].every(c => c instanceof dialog.HTMLInputElement), 'real HTML checkboxes in XHTML namespace');
    const tr = dialog.document.querySelector('#results tr');
    assert(tr instanceof dialog.HTMLTableRowElement && tr.cells.length === 4, 'real table rows and cells');
    function assertLayout() {
      const language = dialog.document.querySelector('.language-result');
      const rect = language.getBoundingClientRect();
      const cell = language.closest('td').getBoundingClientRect();
      const reason = language.closest('td').nextElementSibling.getBoundingClientRect();
      assert(rect.height >= 15 && rect.height <= 50 && rect.width >= 140, 'language control has usable size');
      assert(rect.right <= cell.right && rect.right <= reason.left && rect.bottom <= cell.bottom, 'language control does not overlap reason column or next row');
    }
    await Zotero.Promise.delay(100); assertLayout();
    dialog.resizeTo(760, 700); await Zotero.Promise.delay(100); assertLayout();
    dialog.resizeTo(1100, 760); await Zotero.Promise.delay(100);
    const choose = (item, value) => {
      const control = [...dialog.document.querySelectorAll('.language-choice')].find(e => e.getAttribute('aria-label') === '选择语言：' + item.getField('title'));
      control.closest('td').querySelector('.edit-language').click();
      const fresh = [...dialog.document.querySelectorAll('.language-choice')].find(e => e.getAttribute('aria-label') === '选择语言：' + item.getField('title'));
      const button = [...fresh.querySelectorAll('button')].find(b => b.getAttribute('data-language') === value);
      assert(button && !button.disabled, 'language button available for ' + item.key);
      button.click();
      const updated = [...dialog.document.querySelectorAll('.language-choice')].find(e => e.getAttribute('aria-label') === '选择语言：' + item.getField('title'));
      assert([...updated.querySelectorAll('button')].some(b => b.getAttribute('data-language') === value && b.getAttribute('aria-pressed') === 'true'), 'clicked language visibly selected');
    };
    choose(short, 'en');
    choose(changed, 'en');
    choose(cn, '');
    assert(dialog.document.getElementById('chosen').textContent === '已选 2 项', 'manual selections update checkbox and count');
    assert(!short.getField('language') && !changed.getField('language'), 'manual button change is preview only');
    dialog.document.getElementById('apply').click();
    for (let i = 0; i < 100 && dialog.document.getElementById('scan').disabled; i++) await Zotero.Promise.delay(100);
    assert(!cn.getField('language'), 'manual do-not-fill option excludes detected item');
    assert(short.getField('language') === 'en' && changed.getField('language') === 'en', 'manual override and uncertain item applied');
    assert(dialog.document.getElementById('status').textContent.includes('已补全'), 'dialog completion status');
    dialog.document.getElementById('undo').click();
    for (let i = 0; i < 100 && dialog.document.getElementById('scan').disabled; i++) await Zotero.Promise.delay(100);
    assert(!cn.getField('language'), 'dialog undo action');
    assert(!short.getField('language') && !changed.getField('language'), 'manual overrides can be undone');
    dialog.close();
    api.auto = true;
    const imported = await article('天然气藏中氦气富集机制及其地质控制因素研究');
    for (let i = 0; i < 150 && !imported.getField('language'); i++) await Zotero.Promise.delay(100);
    assert(imported.getField('language') === 'zh-CN', 'automatic completion after item add');
    api.auto = false;
    for (let i = 0; i < 100 && api.busy; i++) await Zotero.Promise.delay(100);
    assert(!cn.getField('language'), 'automatic mode does not mutate old items');
    await api.undo();
    assert(!imported.getField('language'), 'automatic completion is reversible');
    await api.stop();
    assert(!win.document.getElementById('language-completer-menu'), 'menu cleanup on shutdown');
    await IOUtils.writeUTF8(resultPath, JSON.stringify({ ok: true, version: Zotero.version, checks }, null, 2));
  } catch (e) {
    await IOUtils.writeUTF8(resultPath, JSON.stringify({ ok: false, checks, error: String(e), stack: e.stack }, null, 2));
  }
  Services.startup.quit(Components.interfaces.nsIAppStartup.eAttemptQuit);
}
